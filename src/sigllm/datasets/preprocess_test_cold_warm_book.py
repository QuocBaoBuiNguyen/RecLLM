import os
import sys
from pathlib import Path
from typing import Optional

import numpy as np
import pandas as pd

from sigllm.common import NotebookLogger

LOGGER = NotebookLogger.rich_logger("sigllm.data_prep_warm_cold_book")

_REPO_ROOT = Path(__file__).resolve().parents[3]
_DEFAULT_DATA_DIR = os.environ.get(
    "SIGLLM_BOOK_PROCESSED_DIR",
    str(_REPO_ROOT / "data" / "processed" / "amazon-book"),
)


def log_step(title: str, detail: Optional[str] = None) -> None:
    """Emit a compact log line with optional detail string."""
    message = title if detail is None else f"{title} | {detail}"
    LOGGER.info(message)


def process_warm_cold(
    data_dir: str = _DEFAULT_DATA_DIR,
    min_user_inter: int = 3,
    min_item_inter: int = 3,
) -> pd.DataFrame:
    """
    Process train/test data to identify warm and cold interactions based on history.

    Mirrors ``preprocess_test_cold_warm.process_warm_cold`` exactly — the only
    difference is the default ``data_dir`` (Amazon-Book instead of ML-1M).
    Thresholds default to ``>3`` to match the movie pipeline; raise them for
    Amazon-Book if the warm subset turns out too large (~727K train samples
    means many items easily clear a low threshold).

    Input files in data_dir:
    - train_ood2.pkl: training split generated by data_preprocessing_book.py
    - test_ood2.pkl: test split generated by data_preprocessing_book.py

    Output sample:
    uid  iid  label   timestamp   his        his_title          title           genres                  flag  not_cold  warm  cold
    1    10   1       1496174400  [0]        [""]               Some Book ...   Books|Fiction           1     1         1     0
    1    25   0       1496347200  [0, 10]    ["", "Some ..."]   Another Title   Books|Mystery           1     1         0     0

    Added columns:
    - warm = 1 if uid is a warm user and iid is a warm item.
      Warm user/item = interaction count > threshold in train_ood2.pkl.
    - cold = 1 if uid is not in training users and iid is not in training items
      (strict cold-start definition).

    Saved file in data_dir:
    - test_warm_cold_ood2.pkl: test_ood2.pkl with extra warm/cold flags.

    Returns: test DataFrame with warm/cold annotations.
    """

    train_path = os.path.join(data_dir, "train_ood2.pkl")
    test_path = os.path.join(data_dir, "test_ood2.pkl")
    out_path = os.path.join(data_dir, "test_warm_cold_ood2.pkl")

    log_step("[1/5] Load datasets", f"dir={data_dir}")
    train_ = pd.read_pickle(train_path)
    test_ = pd.read_pickle(test_path)
    log_step("Loaded shapes", f"train={train_.shape}, test={test_.shape}")

    log_step("[2/5] Analyze User Interactions", f"Threshold > {min_user_inter}")
    user_info = train_.groupby("uid").agg({"label": "count"})
    all_train_users = set(user_info.index)

    warm_users_df = user_info[user_info["label"] > min_user_inter]
    warm_users_set = set(warm_users_df.index)
    log_step(
        "User stats",
        f"Total={len(all_train_users)}, Warm={len(warm_users_set)}",
    )

    log_step("[3/5] Analyze Item Interactions", f"Threshold > {min_item_inter}")
    item_info = train_.groupby("iid").agg({"label": "count"})
    all_train_items = set(item_info.index)

    warm_items_df = item_info[item_info["label"] > min_item_inter]
    warm_items_set = set(warm_items_df.index)
    log_step(
        "Item stats",
        f"Total={len(all_train_items)}, Warm={len(warm_items_set)}",
    )

    log_step("[4/5] Compute Warm/Cold Flags for Test Set")

    test_["warm"] = test_.apply(
        lambda x: 1
        if (x["uid"] in warm_users_set and x["iid"] in warm_items_set)
        else 0,
        axis=1,
    )

    test_["cold"] = test_.apply(
        lambda x: 1
        if (x["uid"] not in all_train_users and x["iid"] not in all_train_items)
        else 0,
        axis=1,
    )

    stats_warm = test_["warm"].value_counts(normalize=True).get(1, 0)
    stats_cold = test_["cold"].value_counts(normalize=True).get(1, 0)

    log_step("Flag distribution", f"Warm={stats_warm:.1%}, Cold={stats_cold:.1%}")
    log_step(
        "Test DataFrame Stats",
        "\n" + str(test_[["not_cold", "warm", "cold"]].describe()),
    )

    log_step("[5/5] Save Result", f"path={out_path}")
    test_.to_pickle(out_path)

    return test_


if __name__ == "__main__":
    if "src" not in sys.path:
        src_path = "src"
        if not sys.path[0].endswith("src"):
            sys.path.insert(0, src_path)

    process_warm_cold()
